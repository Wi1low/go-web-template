// Package httpserver provides the main gin HTTP server module. It builds the
// middleware chain, mounts every started module that implements route.Routable
// under /api/v1, and owns graceful shutdown of the listener.
//
// This module must be registered last in kernel.New.
package httpserver

import (
	"context"
	"errors"
	"net/http"
	"time"

	_ "github.com/Wi1low/go-web-template/docs" // generated by `make swagger`
	"github.com/Wi1low/go-web-template/internal/config"
	"github.com/Wi1low/go-web-template/internal/kernel"
	"github.com/Wi1low/go-web-template/internal/middleware"
	"github.com/Wi1low/go-web-template/internal/route"
	"github.com/Wi1low/go-web-template/pkg/response"
	"github.com/gin-gonic/gin"
	ginprom "github.com/logocomune/gin-prometheus"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"
	"go.uber.org/zap"
)

type module struct {
	srv *http.Server
}

// New returns the httpserver module.
func New() kernel.Module { return &module{} }

func (*module) Name() string { return "httpserver" }

// Enabled always true: an HTTP template without a server is not a server.
func (*module) Enabled(*config.Config) bool { return true }

func (m *module) Init(_ context.Context, a *kernel.App) error {
	cfg := a.Cfg

	gin.SetMode(ginMode(cfg.Server.Mode))
	engine := gin.New()

	// Global middleware chain. Order matters: RequestID first so everything
	// downstream can attribute work to a trace.
	engine.Use(middleware.RequestID())
	engine.Use(middleware.ZapLogger(zap.L()))
	engine.Use(middleware.Recovery())
	if cfg.Cors.Enabled {
		engine.Use(middleware.Cors(&cfg.Cors))
	}
	if cfg.Prometheus.Enabled {
		// NewMetricsCollection must run exactly once per process: it
		// MustRegisters its collectors on the default prometheus registry.
		mc := ginprom.NewMetricsCollection(
			ginprom.WithMetricPrefix(cfg.Prometheus.Namespace),
		)
		engine.Use(ginprom.MiddlewareWithMetrics(mc,
			ginprom.WithFilterRoutes([]string{"/ping", "/swagger"}),
		))
	}

	engine.GET("/ping", ping)
	if cfg.Swagger.Enabled {
		engine.GET(cfg.Swagger.Path, ginSwagger.WrapHandler(swaggerFiles.Handler))
	}

	// Discover routes from started modules only (Enabled && Init succeeded),
	// so a disabled business module cannot mount dead routes.
	api := engine.Group("/api/v1")
	for _, mod := range a.Started() {
		if r, ok := mod.(route.Routable); ok {
			r.RegisterRoutes(api)
		}
	}

	m.srv = &http.Server{
		Addr:              cfg.Server.Addr,
		Handler:           engine,
		ReadTimeout:       cfg.Server.ReadTimeout,
		WriteTimeout:      cfg.Server.WriteTimeout,
		ReadHeaderTimeout: 5 * time.Second,
	}
	go func() {
		zap.L().Info("http server listening", zap.String("addr", cfg.Server.Addr), zap.String("mode", string(cfg.Server.Mode)))
		if err := m.srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
			a.Fail(err)
		}
	}()

	kernel.Provide(a, engine)
	return nil
}

func (m *module) Stop(ctx context.Context) error {
	if m.srv == nil {
		return nil
	}
	return m.srv.Shutdown(ctx)
}

func ginMode(mode config.Mode) string {
	switch mode {
	case config.ModeDev:
		return gin.DebugMode
	case config.ModeTest:
		return gin.TestMode
	default:
		return gin.ReleaseMode
	}
}

func ping(c *gin.Context) {
	response.Success(c, gin.H{"message": "pong"})
}
